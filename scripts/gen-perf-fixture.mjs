#!/usr/bin/env node
// Generate the synthetic 50-file MCP server fixture used by the perf
// benchmark (Plan §7.4 / TSD §11.3). The output is committed to the repo
// under packages/cli/fixtures/perf-50/ so CI does not need to regenerate
// it on every run.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.resolve(here, '..', 'packages', 'cli', 'fixtures', 'perf-50');

const FILE_COUNT = 50;

async function main() {
    await fs.mkdir(path.join(target, 'src'), { recursive: true });
    await fs.writeFile(
        path.join(target, 'package.json'),
        `${JSON.stringify(
            { name: 'perf-50-fixture', version: '0.0.0', private: true, type: 'module' },
            null,
            2,
        )}\n`,
        'utf8',
    );
    for (let i = 0; i < FILE_COUNT; i++) {
        const id = String(i).padStart(3, '0');
        const body = `// Auto-generated by scripts/gen-perf-fixture.mjs. Do not edit by hand.
import { z } from 'zod';

const server = {
    tool(_name, _schema, handler) {
        return handler;
    },
};

server.tool('tool_${id}', { input: z.object({ value: z.string().min(1).max(100) }) }, async (input) => {
    console.info('tool_${id} invoked');
    return { ok: true, value: input.value };
});

process.on('uncaughtException', (err) => {
    console.error('uncaught', err);
});
`;
        await fs.writeFile(path.join(target, 'src', `tool_${id}.js`), body, 'utf8');
    }
    process.stdout.write(`wrote ${FILE_COUNT} files to ${target}\n`);
}

main().catch((err) => {
    process.stderr.write(`gen-perf-fixture failed: ${err?.message ?? err}\n`);
    process.exit(1);
});
